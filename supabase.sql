-- ---------------------------------------------------------
-- 2) PRODUCTS
-- ---------------------------------------------------------
create table if not exists public.ea_products (
  id uuid primary key default gen_random_uuid(),
  product_code text not null unique,
  product_name text not null,
  sale_price numeric(12,2) not null default 0 check (sale_price >= 0),
  stock_qty numeric(12,2) not null default 0 check (stock_qty >= 0),
  min_stock numeric(12,2) not null default 5 check (min_stock >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_ea_products_name
  on public.ea_products (product_name);

-- ---------------------------------------------------------
-- 3) SALES
-- ---------------------------------------------------------
create table if not exists public.ea_sales (
  id uuid primary key default gen_random_uuid(),
  sale_no text not null unique,
  sale_date date not null default current_date,
  sale_time time not null default localtime,
  total_amount numeric(12,2) not null default 0 check (total_amount >= 0),
  note text,
  created_at timestamptz not null default now()
);

create index if not exists idx_ea_sales_date
  on public.ea_sales (sale_date);

-- ---------------------------------------------------------
-- 4) SALE ITEMS
-- ---------------------------------------------------------
create table if not exists public.ea_sale_items (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.ea_sales(id) on delete cascade,
  product_id uuid not null references public.ea_products(id),
  product_code text not null,
  product_name text not null,
  qty numeric(12,2) not null check (qty > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_total numeric(12,2) generated always as (qty * unit_price) stored,
  created_at timestamptz not null default now()
);

create index if not exists idx_ea_sale_items_sale
  on public.ea_sale_items (sale_id);

create index if not exists idx_ea_sale_items_product
  on public.ea_sale_items (product_id);

-- ---------------------------------------------------------
-- 5) STOCK MOVEMENTS
-- ---------------------------------------------------------
create table if not exists public.ea_stock_movements (
  id uuid primary key default gen_random_uuid(),
  movement_date date not null default current_date,
  movement_time time not null default localtime,
  movement_type text not null
    check (movement_type in ('IN','OUT','SALE','ADJUST')),
  product_id uuid not null references public.ea_products(id),
  product_code text not null,
  product_name text not null,
  qty_change numeric(12,2) not null,
  stock_before numeric(12,2) not null,
  stock_after numeric(12,2) not null check (stock_after >= 0),
  reference_id uuid,
  note text,
  created_at timestamptz not null default now()
);

create index if not exists idx_ea_stock_movements_date
  on public.ea_stock_movements (movement_date);

create index if not exists idx_ea_stock_movements_product
  on public.ea_stock_movements (product_id);

-- ---------------------------------------------------------
-- 6) updated_at trigger
-- ---------------------------------------------------------
create or replace function public.ea_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_ea_products_updated_at on public.ea_products;
create trigger trg_ea_products_updated_at
before update on public.ea_products
for each row execute function public.ea_set_updated_at();

drop trigger if exists trg_ea_settings_updated_at on public.ea_settings;
create trigger trg_ea_settings_updated_at
before update on public.ea_settings
for each row execute function public.ea_set_updated_at();

-- ---------------------------------------------------------
-- 7) RPC: RECORD SALE
-- ทำ Sale + Sale Item + ตัด Stock + Movement ใน Transaction เดียว
-- ---------------------------------------------------------
create or replace function public.ea_record_sale(
  p_product_id uuid,
  p_qty numeric,
  p_unit_price numeric,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_product public.ea_products%rowtype;
  v_sale public.ea_sales%rowtype;
  v_sale_no text;
  v_total numeric(12,2);
  v_after numeric(12,2);
begin
  if p_qty is null or p_qty <= 0 then
    raise exception 'Quantity must be greater than 0';
  end if;

  if p_unit_price is null or p_unit_price < 0 then
    raise exception 'Unit price cannot be negative';
  end if;

  select *
    into v_product
  from public.ea_products
  where id = p_product_id
    and is_active = true
  for update;

  if not found then
    raise exception 'Product not found';
  end if;

  if v_product.stock_qty < p_qty then
    raise exception 'Insufficient stock. Available: %', v_product.stock_qty;
  end if;

  v_total := p_qty * p_unit_price;
  v_after := v_product.stock_qty - p_qty;
  v_sale_no := 'FS-' || to_char(clock_timestamp(), 'YYYYMMDD-HH24MISSMS');

  insert into public.ea_sales (
    sale_no, sale_date, sale_time, total_amount, note
  )
  values (
    v_sale_no, current_date, localtime, v_total, p_note
  )
  returning * into v_sale;

  insert into public.ea_sale_items (
    sale_id, product_id, product_code, product_name,
    qty, unit_price
  )
  values (
    v_sale.id, v_product.id, v_product.product_code, v_product.product_name,
    p_qty, p_unit_price
  );

  update public.ea_products
  set stock_qty = v_after
  where id = v_product.id;

  insert into public.ea_stock_movements (
    movement_type, product_id, product_code, product_name,
    qty_change, stock_before, stock_after, reference_id, note
  )
  values (
    'SALE', v_product.id, v_product.product_code, v_product.product_name,
    -p_qty, v_product.stock_qty, v_after, v_sale.id, coalesce(p_note,'ขายสินค้า')
  );

  return jsonb_build_object(
    'sale_id', v_sale.id,
    'sale_no', v_sale.sale_no,
    'total_amount', v_total,
    'stock_after', v_after
  );
end;
$$;

-- ---------------------------------------------------------
-- 8) RPC: STOCK MOVEMENT
-- รับเข้า / เบิก / ปรับยอด
-- ---------------------------------------------------------
create or replace function public.ea_update_stock(
  p_product_id uuid,
  p_type text,
  p_qty numeric,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_product public.ea_products%rowtype;
  v_before numeric(12,2);
  v_after numeric(12,2);
  v_change numeric(12,2);
  v_type text;
begin
  v_type := upper(trim(p_type));

  if v_type not in ('IN','OUT','ADJUST') then
    raise exception 'Invalid stock movement type';
  end if;

  if p_qty is null or p_qty < 0 then
    raise exception 'Quantity cannot be negative';
  end if;

  select *
    into v_product
  from public.ea_products
  where id = p_product_id
  for update;

  if not found then
    raise exception 'Product not found';
  end if;

  v_before := v_product.stock_qty;

  if v_type = 'IN' then
    v_after := v_before + p_qty;
  elsif v_type = 'OUT' then
    if v_before < p_qty then
      raise exception 'Insufficient stock. Available: %', v_before;
    end if;
    v_after := v_before - p_qty;
  else
    v_after := p_qty;
  end if;

  v_change := v_after - v_before;

  update public.ea_products
  set stock_qty = v_after
  where id = v_product.id;

  insert into public.ea_stock_movements (
    movement_type, product_id, product_code, product_name,
    qty_change, stock_before, stock_after, note
  )
  values (
    v_type, v_product.id, v_product.product_code, v_product.product_name,
    v_change, v_before, v_after, p_note
  );

  return jsonb_build_object(
    'product_id', v_product.id,
    'stock_before', v_before,
    'stock_after', v_after,
    'qty_change', v_change
  );
end;
$$;

